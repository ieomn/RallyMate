"""Export the FS05-M02 application policy, not an original-card grade rubric."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rallymate_scoring.card_rule_catalog import get_card_rule
from rallymate_service import micro_adjustment_cycles as service

OUTPUT = ROOT / "scoring-demo-web/app/lib/micro-cycle-display-contract.ts"


def build_contract():
    source = get_card_rule(service.CARD)["source"]
    return {"runtime_engine": service.VERSION, "measurement_version": service.RULE_VERSION,
        "application_rule_version": service.RULE_VERSION, "annotation_version": service.ANNOTATION_VERSION,
        "episode_policy": service.EPISODE_POLICY, "card_id": service.CARD,
        "required_joint_names": list(service.REQUIRED_JOINTS), "conditions": service.CONDITIONS,
        "low_speed_threshold_torso_s": service.LOW_SPEED_TORSO_S,
        "minimum_phase_duration_ms": service.MIN_PHASE_MS, "minimum_phase_frame_count": service.MIN_PHASE_FRAMES,
        "source": {key: source[key] for key in ("document_id", "document_sha256", "table", "rubric_sha256")}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = "// Generated by scripts/build_micro_cycle_display_contract.py; verify with --check.\nexport default " + json.dumps(build_contract(), ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Micro-cycle application contract differs from backend")
    else:
        OUTPUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
