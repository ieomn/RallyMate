"""Export four mathematical motion policies, never a real-step validation claim."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rallymate_scoring import step_motion_evidence as core
from rallymate_scoring.card_rule_catalog import get_card_rule

OUTPUT = ROOT / "scoring-demo-web/app/lib/fs-step-motion-display-contract.ts"
PREFIX = "// Generated by scripts/build_fs_step_motion_display_contract.py; verify with --check.\nexport default "


def build_contract():
    return {"version": core.VERSION, "policy_version": core.POLICY_VERSION,
        "annotation_version": core.ANNOTATION_VERSION, "annotation_semantics": core.ANNOTATION_SEMANTICS,
        "required_joint_names": list(core.REQUIRED_JOINTS),
        "low_speed_threshold_torso_s": core.LOW_SPEED_TORSO_S,
        "minimum_phase_duration_ms": core.MIN_PHASE_MS,
        "minimum_phase_frame_count": core.MIN_PHASE_FRAMES,
        "cards": {identifier: {"conditions": [[c["metric"], c["operator"], c.get("bounds", c.get("value")), c["unit"]]
            for c in get_card_rule(identifier)["evaluation"]["conditions"]]}
            for identifier in sorted(core.SUPPORTED_CARDS)}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = PREFIX + json.dumps(build_contract(), ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Step motion display contract differs from registered source policy")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print("Verified four synthetic-policy step motion display contracts")


if __name__ == "__main__":
    main()
