"""Export the FS03/FS04 reader contract without claiming video validation."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rallymate_scoring import footwork_cycle_card_evidence as core
from rallymate_service.footwork_cycle_execution import VERSION as RUNTIME_VERSION

OUTPUT = ROOT / "scoring-demo-web/app/lib/footwork-cycle-display-contract.ts"
PREFIX = "// Generated by scripts/build_footwork_cycle_display_contract.py; verify with --check.\nexport default "


def build_contract():
    catalogue = json.loads((ROOT / "src/rallymate_scoring/data/card_rules_v1.json").read_text(encoding="utf-8"))
    cards = {}
    for rule in catalogue["cards"]:
        if rule["event_code"] not in core.SUPPORTED_CODES:
            continue
        cards[rule["indicator_id"]] = {
            "rule_kind": rule["evaluation"]["kind"],
            "limitation": rule["evaluation"]["limitation"],
            "required_joint_names": sorted(set(core.CORE_JOINTS) | set(rule["required_joint_names"])),
            "conditions": [[c["metric"], c["operator"], c.get("bounds", c.get("value")), c["unit"]]
                           for c in rule["evaluation"]["conditions"]],
            "source": {key: rule["source"][key] for key in ("document_id", "document_sha256", "table", "rubric_sha256")},
        }
    return {"rule_version": catalogue["version"], "runtime_engine": RUNTIME_VERSION,
            "measurement_version": core.VERSION, "cycle_policy_version": core.CYCLE_POLICY_VERSION,
            "advisory_quality_policy_version": core.QUALITY_POLICY_VERSION,
            "quality_review_flags": sorted(core.LOCAL_REVIEW_FLAGS),
            "minimum_motion_interval_ms": core.MIN_DURATION_MS,
            "low_ankle_speed_torso_s": core.LOW_ANKLE_SPEED_TORSO_S,
            "order_deadband_torso": core.ORDER_DEADBAND_TORSO, "cards": cards}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = build_contract()
    content = PREFIX + json.dumps(contract, ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("FS03/FS04 reader contract differs from catalogue/core")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print(f"Verified {len(contract['cards'])} FS03/FS04 reader contracts")


if __name__ == "__main__":
    main()
