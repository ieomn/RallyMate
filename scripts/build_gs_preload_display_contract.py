"""Export the five manual-only GS auxiliary contracts, without video claims."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rallymate_scoring import gs_preload_evidence as core
from rallymate_scoring.card_rule_catalog import load_card_rules
from rallymate_scoring.card_kinematics import VERSION as MEASUREMENT_VERSION

OUTPUT = ROOT / "scoring-demo-web/app/lib/gs-preload-display-contract.ts"
PREFIX = "// Generated by scripts/build_gs_preload_display_contract.py; verify with --check.\nexport default "


def build_contract():
    cards = {rule["indicator_id"]: {"stage_code": rule["stage_code"], "rule_kind": rule["evaluation"]["kind"],
        "conditions": rule["evaluation"]["conditions"], "source": {key: rule["source"][key] for key in
        ("document_id", "document_sha256", "table", "rubric_sha256")}}
        for rule in load_card_rules()["cards"] if rule["indicator_id"] in core.SUPPORTED_CARDS}
    return {"version": core.VERSION, "measurement_version": MEASUREMENT_VERSION,
        "annotation_version": core.ANNOTATION_VERSION, "semantics": core.ANNOTATION_SEMANTICS,
        "required_joint_names": list(core.REQUIRED_JOINTS), "references": list(core.AUXILIARY_REFERENCES), "cards": cards}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = PREFIX + json.dumps(build_contract(), ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("GS preload display contract differs from core/catalogue")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print("Verified five manual-only GS preload display contracts")
