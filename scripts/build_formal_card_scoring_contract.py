"""Export only the application scoring policy constants for the browser reader."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rallymate_scoring import card_scoring_policy as policy

OUTPUT = ROOT / "scoring-demo-web/app/lib/formal-card-scoring-contract.ts"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = {"version": policy.SCORING_POLICY_VERSION, "semantics": policy.FORMAL_SCORE_SEMANTICS,
        "legacy_version": policy.LEGACY_SCORING_POLICY_VERSION,
        "supported_versions": list(policy.SUPPORTED_SCORING_POLICY_VERSIONS),
        "score_formula": "100 * passed_condition_count / required_condition_count",
        "grade_points": policy.GRADE_POINTS,
        "advisory_quality_flags": sorted(getattr(policy, "ADVISORY_QUALITY_FLAGS", ())) }
    text = "// Generated by scripts/build_formal_card_scoring_contract.py; verify with --check.\nexport default " + json.dumps(contract, ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("Formal scoring policy reader contract differs from backend constants")
    else:
        OUTPUT.write_text(text, encoding="utf-8")
    print("Verified application formal scoring policy contract")


if __name__ == "__main__":
    main()
