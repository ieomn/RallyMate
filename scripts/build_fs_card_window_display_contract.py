"""Export the manual FS window reader contract; registration is not video validation."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rallymate_scoring.card_kinematics import DYNAMIC_SPECS, SPECS, VERSION as MEASUREMENT_VERSION
from rallymate_scoring.card_rule_catalog import load_card_rules
from rallymate_scoring.footwork_cycle_card_evidence import CYCLE_POLICY_VERSION, LOCAL_REVIEW_FLAGS
from rallymate_vision.pose.metadata import load_keypoint_schemas
from rallymate_service.fs_card_windows import ANNOTATION_VERSION, SEMANTICS, VERSION, supported_rules

OUTPUT = ROOT / "scoring-demo-web/app/lib/fs-card-window-display-contract.ts"
PREFIX = "// Generated by scripts/build_fs_card_window_display_contract.py; verify with --check.\nexport default "


def build_contract():
    cards = {}
    for identifier, rule in supported_rules().items():
        evaluation = rule["evaluation"]
        required = set(rule["required_joint_names"])
        conditions = []
        for condition in evaluation["conditions"]:
            metric = condition["metric"]
            required.update(condition["required_joint_names"])
            spec = DYNAMIC_SPECS.get(metric) or SPECS.get(metric.rpartition(".")[0])
            if spec:
                required.update(spec[0])
            conditions.append([metric, condition["operator"], condition.get("bounds", condition.get("value")), condition["unit"]])
        # Every dynamic ankle metric in card-kinematics v1 is behind the
        # explicit complete-step-cycle gate. This adapter supplies no cycle.
        cycle_metrics = [row[0] for row in conditions if row[0] in DYNAMIC_SPECS and row[0].startswith("ankle_")]
        cards[identifier] = {"rule_kind": evaluation["kind"], "limitation": evaluation["limitation"],
            "required_joint_names": sorted(required), "conditions": conditions,
            "requires_complete_step_cycle": bool(cycle_metrics),
            "source": {key: rule["source"][key] for key in ("document_id", "document_sha256", "table", "rubric_sha256")}}
    return {"rule_version": load_card_rules()["version"], "runtime_engine": VERSION,
        "measurement_version": MEASUREMENT_VERSION, "annotation_version": ANNOTATION_VERSION,
        "annotation_semantics": SEMANTICS, "quality_policy_version": CYCLE_POLICY_VERSION,
        "quality_review_flags": sorted(LOCAL_REVIEW_FLAGS),
        "known_joint_names": sorted({point["name"] for schema in load_keypoint_schemas()["formats"].values() for point in schema["keypoints"]}), "cards": cards}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    contract = build_contract()
    content = PREFIX + json.dumps(contract, ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("FS window display contract differs from registered adapter/catalogue")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
    print(f"Verified {len(contract['cards'])} manual FS window reader contracts")


if __name__ == "__main__":
    main()
