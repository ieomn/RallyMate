"""Export the small, reviewable GS report-reader contract from the source catalogue."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "scoring-demo-web/app/lib/gs-card-display-contract.ts"
PREFIX = "// Generated by scripts/build_gs_card_display_contract.py; verify with --check.\nexport default "


def build_contract(catalogue):
    cards = {}
    for rule in catalogue["cards"]:
        if not rule["event_code"].startswith("GS"):
            continue
        evaluation = rule["evaluation"]
        required = set(rule["required_joint_names"])
        conditions = []
        for condition in evaluation["conditions"]:
            required.update(condition["required_joint_names"])
            required.update(catalogue["metrics"][condition["metric"]]["required_joint_names"])
            conditions.append([condition["metric"], condition["operator"],
                condition.get("bounds", condition.get("value")), condition["unit"]])
        cards[rule["indicator_id"]] = {"stage_code": rule["stage_code"],
            "rule_kind": evaluation["kind"], "required_joint_names": sorted(required),
            "conditions": conditions,
            "source": {key: rule["source"][key] for key in
                ("document_id", "document_sha256", "table", "rubric_sha256")}}
        if evaluation.get("scoring_revision_id"):
            cards[rule["indicator_id"]].update({key: evaluation[key] for key in
                ("scoring_revision_id", "score_block_reason_code", "required_observables")})
    return {"rule_version": catalogue["version"], "runtime_engine": "gs-card-execution-v1.0.0",
        "measurement_version": "card-kinematics-v1.0.0", "cards": cards}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalogue = json.loads((ROOT / "src/rallymate_scoring/data/card_rules_v1.json").read_text(encoding="utf-8"))
    expected = build_contract(catalogue)
    source = PREFIX + json.dumps(expected, ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if DEFAULT_OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("GS display contract differs from the current catalogue")
    else:
        DEFAULT_OUTPUT.write_text(source, encoding="utf-8")
    print(f"Verified {len(expected['cards'])} GS display contracts")


if __name__ == "__main__":
    main()
