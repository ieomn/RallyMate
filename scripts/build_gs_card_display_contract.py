"""Export the small, reviewable GS report-reader contract from the source catalogue."""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "scoring-demo-web/app/lib/gs-card-display-contract.ts"
PREFIX = "// Generated by scripts/build_gs_card_display_contract.py; verify with --check.\nexport default "


def recovery_contract(path):
    """Read literal policy constants only; do not import a runtime dependency tree."""
    keys = ("VERSION", "SCORING_REVISION_ID", "POLICY_VERSION", "REFERENCE_VERSION", "REFERENCE_SEMANTICS",
        "AUXILIARY_VERSION", "ROTATION_CARDS", "STABILITY_CARDS", "MANUAL_REQUIREMENTS",
        "ROTATION_CONDITIONS", "STABILITY_CONDITIONS", "MIN_RECOVERY_FRAMES", "MIN_REFERENCE_FRAMES",
        "MIN_WINDOW_MS", "REFERENCE_MAX_AXIS_RANGE_DEG", "MIN_AXIS_LENGTH_TORSO", "ENDPOINT_FRACTION", "MIN_ENDPOINT_FRAMES")
    result = {}
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1 or not isinstance(node.targets[0], ast.Name):
            continue
        name = node.targets[0].id
        if name not in keys:
            continue
        value = node.value
        if isinstance(value, ast.Call) and isinstance(value.func, ast.Name) and value.func.id == "frozenset" and len(value.args) == 1:
            value = value.args[0]
        result[name.lower()] = ast.literal_eval(value)
    if len(result) != len(keys):
        raise ValueError("Recovery display policy constants are incomplete")
    return result


def build_contract(catalogue, recovery=None):
    cards = {}
    for rule in catalogue["cards"]:
        if not rule["event_code"].startswith("GS"):
            continue
        evaluation = rule["evaluation"]
        required = set(rule["required_joint_names"])
        conditions = []
        for condition in evaluation["conditions"]:
            required.update(condition["required_joint_names"])
            required.update(catalogue["metrics"][condition["metric"]]["required_joint_names"])
            conditions.append([condition["metric"], condition["operator"],
                condition.get("bounds", condition.get("value")), condition["unit"]])
        cards[rule["indicator_id"]] = {"stage_code": rule["stage_code"],
            "rule_kind": evaluation["kind"], "required_joint_names": sorted(required),
            "conditions": conditions,
            "source": {key: rule["source"][key] for key in
                ("document_id", "document_sha256", "table", "rubric_sha256")}}
        if evaluation.get("scoring_revision_id"):
            keys = ("scoring_revision_id", "score_block_reason_code", "required_observables")
            if evaluation["scoring_revision_id"] == "gs-m10-observability-v1.0.0":
                keys += ("required_engine",)
            cards[rule["indicator_id"]].update({key: evaluation[key] for key in keys if key in evaluation})
    return {"rule_version": catalogue["version"], "runtime_engine": "gs-card-execution-v1.0.0",
        "measurement_version": "card-kinematics-v1.0.0", "cards": cards,
        **({"recovery": recovery} if recovery is not None else {})}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalogue = json.loads((ROOT / "src/rallymate_scoring/data/card_rules_v1.json").read_text(encoding="utf-8"))
    expected = build_contract(catalogue, recovery_contract(ROOT / "src/rallymate_scoring/gs_recovery_evidence.py"))
    source = PREFIX + json.dumps(expected, ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if DEFAULT_OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("GS display contract differs from the current catalogue")
    else:
        DEFAULT_OUTPUT.write_text(source, encoding="utf-8")
    print(f"Verified {len(expected['cards'])} GS display contracts")


if __name__ == "__main__":
    main()
