"""Export the two explicit application rules without changing original rubrics."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from rallymate_scoring import direction_reference_observables as core
from rallymate_scoring.card_rule_catalog import get_card_rule
from rallymate_service import directional_micro_adjustment as service

OUTPUT = ROOT / "scoring-demo-web/app/lib/directional-micro-display-contract.ts"


def build_contract():
    return {"measurement_version": core.VERSION, "runtime_engine": service.VERSION,
        "application_rule_version": service.RULE_VERSION, "annotation_version": service.ANNOTATION_VERSION,
        "reference_version": core.REFERENCE_VERSION, "reference_semantics": core.REFERENCE_SEMANTICS,
        "required_joint_names": list(core.REQUIRED_JOINTS),
        "conditions": service.CONDITIONS,
        "cards": {identifier: {"axis_role": role, "source": {key: get_card_rule(identifier)["source"][key]
                  for key in ("document_id", "document_sha256", "table", "rubric_sha256")}}
                  for identifier, role in service.SUPPORTED_CARDS.items()}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = "// Generated by scripts/build_directional_micro_display_contract.py; verify with --check.\nexport default " + json.dumps(build_contract(), ensure_ascii=False, indent=2) + ";\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Directional micro application contract differs from backend")
    else:
        OUTPUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
